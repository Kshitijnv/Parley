// Screenshots every in-scope screen and its main states into replica/clone-screens
// for /replica-diff, and fails if any page logs a console error.
// Usage: npm run dev:web (another shell), then npm run screens
import { chromium } from 'playwright'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

const BASE = process.env.BASE ?? 'http://localhost:5199/'
const OUT = resolve(import.meta.dirname, '../../replica/clone-screens')
mkdirSync(OUT, { recursive: true })

const browser = await chromium.launch({ channel: 'msedge', headless: true })
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
await ctx.grantPermissions(['clipboard-read', 'clipboard-write'])
const page = await ctx.newPage()
const errors = []
page.on('console', (m) => {
  if (m.type() === 'error' && !m.text().includes('favicon')) errors.push(`${page.url()} :: ${m.text()}`)
})
page.on('pageerror', (e) => errors.push(`${page.url()} :: ${e}`))

const done = []
async function shot(id, note = '') {
  await page.waitForTimeout(250)
  await page.screenshot({ path: `${OUT}/${id}.png` })
  done.push(`${id}${note ? ` (${note})` : ''}`)
  console.log('saved', id)
}
async function fresh(kind = 'seed', scenario = '') {
  await page.goto(`${BASE}#/overlay`)
  await page.evaluate(([k, s]) => {
    localStorage.clear()
    if (s) localStorage.setItem('parley:mock', s)
    if (k === 'empty') localStorage.setItem('parley:mock', s ? `${s},empty` : 'empty')
  }, [kind, scenario])
  await page.goto(`${BASE}#/overlay`)
  await page.reload()
  await page.waitForTimeout(300)
}
const go = async (hash) => {
  await page.goto(`${BASE}#${hash}`)
  await page.waitForTimeout(400)
}

