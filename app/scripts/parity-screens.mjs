// Window-only screenshots for /replica-diff: the overlay frame (what the Electron window shows,
// since main sizes the window to the frame) in the states the reference photos show.
// Writes replica/clone-screens/win/<screen>.png. Usage: npm run dev:web, then node scripts/parity-screens.mjs
import { chromium } from 'playwright'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

const BASE = process.env.BASE ?? 'http://localhost:5199/'
const OUT = resolve(import.meta.dirname, '../../replica/clone-screens/win')
mkdirSync(OUT, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
const frame = page.locator('[data-testid="overlay-window"] > div').first()

async function win(id, target = frame) {
  await page.waitForTimeout(300)
  await target.screenshot({ path: `${OUT}/${id}.png` })
  console.log('saved', id)
}
async function view(id) {
  await page.waitForTimeout(300)
  await page.screenshot({ path: `${OUT}/${id}.png` })
  console.log('saved', id)
}
async function fresh(empty = false, scenario = '') {
  await page.goto(`${BASE}#/overlay`)
  await page.evaluate(([e, s]) => {
    localStorage.clear()
    const m = [s, e && 'empty'].filter(Boolean).join(',')
    if (m) localStorage.setItem('parley:mock', m)
  }, [empty, scenario])
  await page.reload()
  await page.waitForTimeout(300)
}
// bar + strip only (the reference S13 photo has no answer panel)
async function barAndStrip(id) {
  await page.waitForTimeout(300)
  const a = await page.getByRole('toolbar', { name: 'Call controls' }).boundingBox()
  const f = await frame.boundingBox()
  const strip = await page.getByRole('button', { name: /Expand transcript/ }).boundingBox()
  await page.screenshot({ path: `${OUT}/${id}.png`, clip: { x: f.x, y: a.y, width: f.width, height: strip.y + strip.height + 4 - a.y } })
  console.log('saved', id)
}

